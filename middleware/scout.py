"""
Scout Agent module for HelixGuard (Milestone 6).
Proposes sequence location hints (anchors and candidate quotes) from documents.

CRITICAL INTEGRITY RULES:
1. Scout output is a PROPOSAL, never ground truth.
2. Scout never generates, repairs, normalizes, or guesses nucleotides.
3. Every proposal must pass strict deterministic verification in extraction.py.
4. Bounded retries: maximum 3 attempts, observable audit log.
5. Deterministic fallback when Ollama is unavailable.
"""

import os
import json
import logging
import re
from typing import List, Optional, Dict, Any, Tuple
from pydantic import BaseModel, Field
import httpx

from middleware.critic import ContextCritic
from middleware.llm_client import OllamaClient, default_llm_client
from middleware.masking import mask_document_for_llm, dereference_token, MaskedDocument

logger = logging.getLogger("helixguard.scout")


class ScoutProposal(BaseModel):
    """Proposal generated by Scout agent for sequence localization."""
    field_type: str = Field("observed_sequence", description="Semantic field being located")
    candidate_quote: str = Field(..., description="Exact excerpt from document containing sequence")
    anchor_before: Optional[str] = Field(None, description="Exact text immediately preceding sequence")
    anchor_after: Optional[str] = Field(None, description="Exact text immediately following sequence")
    expected_alphabet: str = Field("DNA", description="Expected sequence alphabet (DNA/RNA)")
    reason: str = Field("", description="Justification explaining why this excerpt was selected")


class ScoutAttemptRecord(BaseModel):
    """Audit record for a single Scout attempt in the retry loop."""
    attempt_number: int
    proposal: Optional[ScoutProposal] = None
    verification_success: bool = False
    failure_reason: Optional[str] = None


class ScoutAgent:
    """
    Scout localization agent with LLM integration and deterministic fallback.
    """

    def __init__(
        self,
        ollama_url: Optional[str] = None,
        model: Optional[str] = None,
        timeout_seconds: float = 3.0,
        max_attempts: int = 3,
        llm_client: Optional[OllamaClient] = None,
    ) -> None:
        self.client = llm_client or OllamaClient(
            base_url=ollama_url,
            model=model or os.getenv("OLLAMA_MODEL", "gemma4:31b"),
            timeout_seconds=timeout_seconds,
        )
        self.max_attempts = max_attempts

    def propose_deterministic(
        self,
        document_text: str,
        field_type: str = "observed_sequence",
        alphabet: str = "DNA",
        previous_failure: Optional[str] = None
    ) -> Optional[ScoutProposal]:
        """
        Purely deterministic localization proposal using regex pattern scanning.
        Acts as reliable fallback when Ollama is offline or unconfigured.
        """
        if not document_text.strip():
            return None

        # Look for field labels like "Observed sequence:", "Variant sequence:", etc.
        field_norm = field_type.replace("_", r"[\s_-]*")
        pattern = re.compile(
            rf"(?P<before>(?:{field_norm}|observed(?:\s+sequence)?|sample|query)\s*[:=]\s*)(?P<quote>[A-Za-z0-9\s\n]+?)(?=(?:\n[A-Za-z0-9_-]+:|\n\s*\n|$))",
            re.IGNORECASE
        )

        match = pattern.search(document_text)
        if match:
            anchor_before = match.group("before").strip()
            raw_quote = match.group("quote").strip()

            # Find following anchor if available
            end_pos = match.end()
            after_text = document_text[end_pos:].strip()
            anchor_after = None
            if after_text:
                first_line = after_text.splitlines()[0]
                if ":" in first_line:
                    anchor_after = first_line.split(":")[0] + ":"

            # Extract bases from the quote
            clean_bases = re.sub(r"[^A-Za-z]", "", raw_quote)
            if clean_bases:
                return ScoutProposal(
                    field_type=field_type,
                    candidate_quote=clean_bases,
                    anchor_before=anchor_before,
                    anchor_after=anchor_after,
                    expected_alphabet=alphabet,
                    reason=f"Deterministically located candidate under '{anchor_before}'"
                )

        # Fallback: scan for any contiguous nucleotide block (>=6 bases)
        base_re = r"[ACGTacgt]{6,}" if alphabet.upper() == "DNA" else r"[ACGUacgu]{6,}"
        seq_match = re.search(rf"\b({base_re})\b", document_text)
        if seq_match:
            candidate = seq_match.group(1).upper()
            start, end = seq_match.span()
            before = document_text[max(0, start - 25):start].strip()
            after = document_text[end:min(len(document_text), end + 25)].strip()
            return ScoutProposal(
                field_type=field_type,
                candidate_quote=candidate,
                anchor_before=before or None,
                anchor_after=after or None,
                expected_alphabet=alphabet,
                reason="Deterministically identified nucleotide sequence token in document."
            )

        return None

    def propose_with_token_mask(
        self,
        document_text: str,
        field_type: str = "observed_sequence",
        alphabet: str = "DNA",
        previous_failure: Optional[str] = None
    ) -> Optional[ScoutProposal]:
        """
        Privacy-preserving token-masked Scout localization (Round 2 Hardening).
        Replaces all nucleotides and patient IDs with tokens so the LLM NEVER sees bases.
        The LLM only identifies WHICH token matches the requested field.
        """
        masked_doc = mask_document_for_llm(document_text, alphabet=alphabet)
        if not masked_doc.tokens:
            logger.info("No sequence tokens detected during masking, falling back to deterministic.")
            return None

        token_list_str = ", ".join(f"'{t.token}'" for t in masked_doc.tokens)

        prompt = (
            f"You are the Scout agent for privacy-preserving genomic document analysis.\n"
            f"All nucleotide sequences and patient identifiers in the document have been tokenized for security.\n"
            f"Available sequence tokens: [{token_list_str}].\n"
            f"Task: Identify which sequence token belongs to field '{field_type}' based strictly on the surrounding context.\n"
            f"RULES:\n"
            f"1. Choose ONLY from the available sequence tokens: [{token_list_str}].\n"
            f"2. Return JSON ONLY with keys:\n"
            f"   - 'field_type': '{field_type}'\n"
            f"   - 'selected_token': the token string (e.g. '<SEQ_0, 48 nt>')\n"
            f"   - 'anchor_before': text immediately preceding the token in the document\n"
            f"   - 'anchor_after': text immediately following the token in the document\n"
            f"   - 'expected_alphabet': '{alphabet}'\n"
            f"   - 'reason': brief explanation of context match\n"
        )
        if previous_failure:
            prompt += f"NOTE: Previous attempt failed with reason: '{previous_failure}'. Propose a DIFFERENT token.\n"

        prompt += f"\nSanitized Document:\n'''\n{masked_doc.masked_text}\n'''\nJSON:"

        try:
            logger.info("Scout querying LLM in token-masked mode (%d tokens, model=%s)...", len(masked_doc.tokens), self.client.model)
            response_text = self.client.generate(prompt, format_json=True)
            if response_text:
                clean_text = response_text.strip()
                if clean_text.startswith("```"):
                    clean_text = re.sub(r"^```[a-zA-Z]*\s*", "", clean_text)
                    clean_text = re.sub(r"\s*```$", "", clean_text)
                parsed = json.loads(clean_text)

                selected_token = parsed.get("selected_token") or parsed.get("candidate_quote")
                if selected_token:
                    token_info = dereference_token(str(selected_token), masked_doc.token_map)
                    if token_info:
                        logger.info("Token-masked Scout resolved token '%s' to %d nt sequence.", token_info.token, token_info.length)
                        return ScoutProposal(
                            field_type=parsed.get("field_type", field_type),
                            candidate_quote=token_info.raw_sequence,
                            anchor_before=str(parsed.get("anchor_before", "")).strip() or None,
                            anchor_after=str(parsed.get("anchor_after", "")).strip() or None,
                            expected_alphabet=parsed.get("expected_alphabet", alphabet),
                            reason=f"Privacy token-masked scout matched {token_info.token}: {parsed.get('reason', '')}"
                        )
                    else:
                        logger.warning("Scout proposed unknown token '%s', falling back.", selected_token)
        except Exception as exc:
            logger.warning("Token-masked LLM query failed (%s). Falling back.", exc)

        return None

    def _propose_with_raw_llm(
        self,
        document_text: str,
        field_type: str = "observed_sequence",
        alphabet: str = "DNA",
        previous_failure: Optional[str] = None
    ) -> Optional[ScoutProposal]:
        """Legacy quote-based LLM proposal, kept as opt-in fallback."""
        prompt = (
            f"You are the Scout agent for genomic document analysis.\n"
            f"Task: Locate the sequence for field '{field_type}' in the document below.\n"
            f"RULES:\n"
            f"1. Quote EXACT text from the document only. Do not invent or modify bases.\n"
            f"2. Return JSON ONLY with keys: field_type, candidate_quote, anchor_before, anchor_after, expected_alphabet, reason.\n"
        )
        if previous_failure:
            prompt += f"NOTE: Previous attempt failed with reason: '{previous_failure}'. Propose a DIFFERENT exact excerpt.\n"

        prompt += f"\nDocument:\n'''\n{document_text}\n'''\nJSON:"

        try:
            logger.info("Scout agent querying Ollama (%s) for field '%s'...", self.client.model, field_type)
            response_text = self.client.generate(prompt, format_json=True)
            if response_text:
                clean_text = response_text.strip()
                if clean_text.startswith("```"):
                    clean_text = re.sub(r"^```[a-zA-Z]*\s*", "", clean_text)
                    clean_text = re.sub(r"\s*```$", "", clean_text)
                parsed = json.loads(clean_text)
                if "candidate_quote" in parsed and parsed["candidate_quote"]:
                    prop = ScoutProposal(
                        field_type=parsed.get("field_type", field_type),
                        candidate_quote=str(parsed["candidate_quote"]).strip(),
                        anchor_before=str(parsed.get("anchor_before", "")).strip() or None,
                        anchor_after=str(parsed.get("anchor_after", "")).strip() or None,
                        expected_alphabet=parsed.get("expected_alphabet", alphabet),
                        reason=str(parsed.get("reason", "Ollama scout localization"))
                    )
                    logger.info("Scout agent proposal received: candidate_quote='%s', anchors='%s'/'%s'", prop.candidate_quote, prop.anchor_before, prop.anchor_after)
                    return prop
        except Exception as exc:
            logger.warning("Ollama scout request failed or unavailable (%s). Falling back to deterministic proposal.", exc)

        return None

    def propose_with_llm(
        self,
        document_text: str,
        field_type: str = "observed_sequence",
        alphabet: str = "DNA",
        previous_failure: Optional[str] = None,
        use_token_mask: Optional[bool] = None,
    ) -> Optional[ScoutProposal]:
        """
        Queries Ollama to propose a candidate excerpt and anchors.
        Defaults to privacy-preserving token-masked mode so no raw nucleotides are transmitted.
        Fails safely and falls back to deterministic proposal.
        """
        if use_token_mask is None:
            # Token mask enabled by default; explicitly forced if cloud endpoint is used
            use_token_mask = os.getenv("OLLAMA_TOKEN_MASK", "true").lower() in ("true", "1", "yes")

        if use_token_mask:
            prop = self.propose_with_token_mask(document_text, field_type, alphabet, previous_failure)
            if prop:
                return prop

        # Opt-in raw mode if token mask didn't resolve or was disabled
        raw_prop = self._propose_with_raw_llm(document_text, field_type, alphabet, previous_failure)
        if raw_prop:
            return raw_prop

        # Fallback to deterministic proposal
        return self.propose_deterministic(document_text, field_type, alphabet, previous_failure)

